# Використовується для підбиття підсумку brain-сесії
BRAIN_CONCLUDE_NOTE = """\
Користувач натиснув "Записати висновок" і завершує сесію "Розібрати 🧠".
Підбий підсумок розбору в одне-два речення як ідею.
intent — "idea", extracted.shelf_type — "idea", extracted.content — стислий підсумок-висновок для полиці.
"""


from datetime import datetime, timezone, timedelta
from zoneinfo import ZoneInfo

def build_system_prompt(display_name: str, snapshot: str) -> str:
    kyiv_now = datetime.now(ZoneInfo("Europe/Kyiv"))
    kyiv_str = kyiv_now.strftime("%Y-%m-%d %H:%M (Europe/Kyiv)")
    prompt = MASTER_PROMPT.replace("{current_kyiv_time}", kyiv_str)
    parts = [prompt, PERSONAL_GLOSSARY]
    if display_name:
        parts.append(f"Звертайся до користувача на ім'я: {display_name}.")
    parts.append(snapshot)
    return "\n\n".join(parts)
